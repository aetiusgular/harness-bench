#!/usr/bin/env node
// Writes tests/red/manifest.json from the redTest(...) calls in tests/red/*.test.mjs.
// Run it after changing a red test (P2 or P4 only): node tests/red/build-manifest.mjs
// With --check it exits 1 when the manifest on disk differs (tests/contract runs that).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const re = /redTest\(\s*"(P3[a-z]-[a-z0-9-]+)",\s*"([^"]+)",\s*"([a-z]+\.[A-Za-z]+)"/g;
const tests = [];
for (const f of readdirSync(dir).filter((n) => n.endsWith(".test.mjs")).sort()) {
  const src = readFileSync(path.join(dir, f), "utf8");
  for (const [, id, caseText, stub] of src.matchAll(re)) {
    tests.push({
      id,
      lane: id.slice(0, 3),
      case: caseText,
      cmd: `node --test --test-name-pattern='^${id}$' tests/red/${f}`,
      expect: `HB not implemented: ${stub.replace(".", "\\.")}`,
      timeout: 120,
    });
  }
}
const out = JSON.stringify({ "$comment": "Generated by tests/red/build-manifest.mjs from the redTest calls; do not edit by hand. Format: tests/red/README.md.", tests }, null, 2) + "\n";
const file = path.join(dir, "manifest.json");
if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(file, "utf8"); } catch {}
  if (cur !== out) { console.error("tests/red/manifest.json is stale: run node tests/red/build-manifest.mjs"); process.exit(1); }
  console.log(`manifest current: ${tests.length} tests`);
} else {
  writeFileSync(file, out);
  console.log(`wrote ${tests.length} tests`);
}
